import { test, expect } from '@playwright/test';
import { login,createSection,expectPoints,recordScore } from './ui-helpers.js';
test('two students create/join, save scores, revise shared weights and delete owner data',async({page,context},testInfo)=>{
  await login(page,'browser-creator-'+testInfo.project.name);
  await createSection(page);await expectPoints(page,0);
  const code=(await page.getByText(/รหัสเข้าร่วม:/).textContent()).match(/รหัสเข้าร่วม:\s*([A-Z0-9]{6})/)[1];
  await recordScore(page,'Midterm',80);await expectPoints(page,32);
  const friend=await context.newPage();await login(friend,'browser-classmate-'+testInfo.project.name);
  await friend.getByRole('navigation').getByRole('button',{name:'เพิ่มรายวิชา',exact:true}).click();
  await friend.getByRole('button',{name:/เข้าร่วมกลุ่มเรียน/}).click();
  await friend.getByLabel('รหัสเข้าร่วมกลุ่มเรียน',{exact:true}).fill(code);
  await friend.getByRole('button',{name:'เข้าร่วมกลุ่มเรียน',exact:true}).click();
  await friend.getByRole('button',{name:'ไปที่รายวิชา'}).click();await expectPoints(friend,0);
  await expect(friend.getByRole('button',{name:'แก้ไขโครงสร้างร่วม'})).toHaveCount(0);
  await recordScore(friend,'Midterm',60);await expectPoints(friend,24);
  await page.getByRole('button',{name:'แก้ไขโครงสร้างร่วม'}).click();
  await page.getByLabel('Midterm น้ำหนักที่แก้ไข').fill('30');
  await expect(page.getByText('เพิ่มอีก 10% ให้ครบ 100%')).toBeVisible();
  await expect(page.getByRole('button',{name:'บันทึกโครงสร้างร่วม'})).toBeDisabled();
  await page.getByLabel('Final น้ำหนักที่แก้ไข').fill('70');
  await page.getByRole('checkbox',{name:/ฉันตรวจสอบน้ำหนักและประเภทรายการ/}).check();
  await page.getByRole('button',{name:'บันทึกโครงสร้างร่วม'}).click();await expectPoints(page,24);
  await expect(page.getByText('คะแนนดิบ: 80 / 100')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('course-revision.png'),fullPage:true});
  await page.getByRole('button',{name:/เกรดเป้าหมาย A/}).click();
  await page.getByRole('button',{name:'บันทึกเป้าหมายและคำนวณ'}).click();
  await expect(page.getByText(/คะแนนที่ต้องได้ในส่วนที่เหลือ:/)).toContainText('80%');
  await page.screenshot({path:testInfo.outputPath('target-grade.png'),fullPage:true});
  await friend.getByRole('button',{name:'รีเฟรชรายวิชาและน้ำหนัก'}).click();await expectPoints(friend,18);
  await expect(friend.getByText(/ผู้สร้างแก้ไขโครงสร้างการประเมินแล้ว/)).toBeVisible();
  await expect(friend.getByText('คะแนนดิบ: 60 / 100')).toBeVisible();
  await page.getByRole('navigation').getByRole('button',{name:'ความเป็นส่วนตัว'}).click();
  await page.getByRole('checkbox',{name:/ฉันยืนยันการลบข้อมูล/}).check();
  await page.getByRole('button',{name:'ลบข้อมูลของฉัน',exact:true}).click();
  await expect(page.getByRole('button',{name:'ยินยอมและดำเนินการต่อ'})).toBeVisible();
  await expect(page.getByText('คะแนนดิบ: 80 / 100')).toHaveCount(0);
  await friend.getByRole('button',{name:'รีเฟรชรายวิชาและน้ำหนัก'}).click();await expectPoints(friend,18);await friend.close();
});
